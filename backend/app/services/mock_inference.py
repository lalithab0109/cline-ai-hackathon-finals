"""Deterministic mock inference for the development phase.

Returns a STABLE demonstration response per supported test type, matching the
agreed `ScanAnalysisResponse` contract so the real OpenCV -> SVR -> SVM
pipeline can replace it without any frontend change.

Honesty rules enforced here:
- No randomness: every test type maps to one fixed fictional fixture.
- All values are flagged simulated (`is_simulated=True`, `source="mock"`,
  `clinically_validated=False`).
- `image_analysis` is always None: mock mode extracts NO features from the
  uploaded photo, and the explanation says so explicitly.
- Quality sub-metrics (blur score, calibration error) are left null because
  no real image analysis runs in mock mode; `passed` simply reflects that
  file-level validation succeeded before inference was invoked.
"""

from __future__ import annotations

from typing import Any, Optional

from ..config import SIMULATION_DISCLAIMER
from ..schemas import (
    Classification,
    DataSource,
    Explanation,
    Measurement,
    ModelDescriptor,
    QualityResult,
    ScanAnalysisResponse,
    ScanStatus,
    TestType,
)

# Provenance descriptor reported in every mock analysis response.
MOCK_MODEL = ModelDescriptor(
    identifier="aarogya-bindu-mock-inference",
    version="0.1.0",
    kind="mock",
)

# Fixed fictional demonstration fixtures — one per test type, never random.
_FIXTURES: dict[TestType, dict[str, Any]] = {
    TestType.HEMOGLOBIN: {
        "value": 9.2,
        "unit": "g/dL",
        "label": "moderate_abnormality",
        "summary": (
            "Illustrative hemoglobin screening result for a fictional "
            "demo profile; not a medical diagnosis."
        ),
    },
    TestType.GLUCOSE: {
        "value": 152.0,
        "unit": "mg/dL",
        "label": "moderate_abnormality",
        "summary": (
            "Illustrative glucose screening result for a fictional "
            "demo profile; not a medical diagnosis."
        ),
    },
    TestType.URINE_ALBUMIN: {
        "value": 45.0,
        "unit": "mg/L",
        "label": "mild_abnormality",
        "summary": (
            "Illustrative urine albumin screening result for a fictional "
            "demo profile; not a medical diagnosis."
        ),
    },
}

_LIMITATIONS = [
    "Synthetic demonstration data generated by a deterministic mock service.",
    "Not clinically validated; cannot diagnose, treat, or rule out any condition.",
    "No image features were extracted: mock mode does not analyze the uploaded photo.",
    "Real screening thresholds require validated, test-specific clinical criteria.",
]

_MOCK_WARNING = (
    "Mock inference is active: the measurement and classification are fixed "
    "demonstration fixtures and were NOT derived from the uploaded image."
)


def build_mock_result(
    *,
    scan_id: str,
    test_type: TestType,
    age: int,
    sex: Optional[str],
) -> ScanAnalysisResponse:
    """Build the stable success response for a validated scan upload."""

    fixture = _FIXTURES[test_type]
    inputs_used = ["simulated measurement", "age"]
    if sex:
        inputs_used.append("sex")

    return ScanAnalysisResponse(
        scan_id=scan_id,
        report_id=None,  # reports/PDF arrive in a later iteration
        test_type=test_type,
        status=ScanStatus.SUCCESS,
        source=DataSource.MOCK,
        clinically_validated=False,
        model=MOCK_MODEL,
        quality=QualityResult(
            passed=True,
            blur_score=None,
            calibration_detected=None,
            calibration_error=None,
            issues=[],
        ),
        image_analysis=None,
        measurement=Measurement(
            value=fixture["value"],
            unit=fixture["unit"],
            method="mock",
            is_simulated=True,
        ),
        classification=Classification(
            label=fixture["label"],
            method="mock_svm_demo",
            is_simulated=True,
        ),
        explanation=Explanation(
            summary=fixture["summary"],
            inputs_used=inputs_used,
            limitations=list(_LIMITATIONS),
            warnings=[_MOCK_WARNING],
        ),
        disclaimer=SIMULATION_DISCLAIMER,
    )


def build_failed_result(
    *,
    scan_id: str,
    test_type: TestType,
    issues: list[str],
) -> ScanAnalysisResponse:
    """Build a failed-quality response: never a measurement or classification."""

    return ScanAnalysisResponse(
        scan_id=scan_id,
        report_id=None,
        test_type=test_type,
        status=ScanStatus.QUALITY_FAILED,
        source=DataSource.MOCK,
        clinically_validated=False,
        model=MOCK_MODEL,
        quality=QualityResult(passed=False, issues=issues),
        image_analysis=None,
        measurement=None,
        classification=None,
        explanation=Explanation(
            summary=(
                "The uploaded image did not pass validation, so no "
                "screening result was generated. Please retake the photo "
                "and try again."
            ),
            inputs_used=[],
            limitations=list(_LIMITATIONS),
            warnings=[
                "No measurement or classification was produced for this scan."
            ],
        ),
        disclaimer=SIMULATION_DISCLAIMER,
    )
